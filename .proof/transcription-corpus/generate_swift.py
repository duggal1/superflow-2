#!/usr/bin/env python3
"""Generate Agent 1's owned Swift test file from corpus.json."""
import json, os

HERE = os.path.dirname(os.path.abspath(__file__))
corpus = json.load(open(os.path.join(HERE, "corpus.json"), encoding="utf-8"))
samples = corpus["samples"]

def sw(s):
    # json.dumps with ensure_ascii=False yields valid Swift string escapes for
    # quotes, backslashes and control chars; unicode stays literal.
    return json.dumps(s, ensure_ascii=False)

# representative executed subset: 10 short + 10 long, spread across indices
short = [s for s in samples if s["tier"] == "short"]
long = [s for s in samples if s["tier"] == "long"]
exec_ids = []
for tier_list, step in ((short, 10), (long, 10)):
    for i in range(0, len(tier_list), step):
        exec_ids.append(tier_list[i]["id"])
        if len([x for x in exec_ids if x.startswith(tier_list[0]["id"][:5])]) >= 10:
            break
# ensure exactly 10 per tier
exec_ids = [s["id"] for s in short[::10][:10]] + [s["id"] for s in long[::10][:10]]

lines = []
w = lines.append
w("import XCTest")
w("import Foundation")
w("import SuperflowKernel")
w("")
w("private func a1Contains(_ haystack: String, _ needle: String) -> Bool {")
w("    let h = haystack.lowercased(), n = needle.lowercased()")
w("    let wordish = n.unicodeScalars.allSatisfy { c in")
w("        (c.value >= 97 && c.value <= 122) || (c.value >= 48 && c.value <= 57) || c.value == 32")
w("    }")
w("    let numeric = n.filter { $0 != \" \" }.allSatisfy { $0.isNumber }")
w("    let suffix = numeric ? \"\" : \"(?!\\\\w)\"")
w("    if wordish, let rx = try? NSRegularExpression(")
w("        pattern: \"(?<!\\\\w)\" + NSRegularExpression.escapedPattern(for: n) + suffix) {")
w("        return rx.firstMatch(in: h, range: NSRange(h.startIndex..., in: h)) != nil")
w("    }")
w("    return h.contains(n)")
w("}")
w("")
w("import SuperflowPorts")
w("@testable import SuperflowTextPipeline")
w("")
w("/// Agent 1 — extreme transcription quality corpus (short + long tiers).")
w("///")
w("/// 200 deliberately-broken ASR fixtures. FULL corpus is delivered as data and")
w("/// validated structurally by `testFullCorpusFixtureIntegrity`. Only a small")
w("/// representative subset (20) is EXECUTED through the real pipeline, gated by")
w("/// `SUPERFLOW_CORPUS_EXECUTE=1` (machine-throttle safety). Executed samples")
w("/// are scored on five dimensions using required/forbidden token assertions and")
w("/// the verdicts are written to `SUPERFLOW_CORPUS_OUTPUT` as JSON; the 180")
w("/// non-executed samples are reported as NOT EXERCISED, never as PASS.")
w("struct A1DimAssert: Sendable {")
w("    let requiredAny: [[String]]")
w("    let forbidden: [String]")
w("}")
w("struct A1Dims: Sendable {")
w("    let facts, grammar, terms, format, novel: A1DimAssert")
w("}")
w("struct A1Sample: Sendable {")
w("    let id: String, tier: String, domain: String, raw: String")
w("    let wordCount: Int")
w("    let requiredAll: [String]")
w("    let requiredAny: [[String]]")
w("    let forbidden: [String]")
w("    let dims: A1Dims")
w("}")
w("")
w("final class AggressiveCorpusShortTests: XCTestCase {")
w("")
w("    private let corpus: [A1Sample] = [")

for s in samples:
    w("        A1Sample(")
    w(f"            id: {sw(s['id'])}, tier: {sw(s['tier'])}, domain: {sw(s['domain'])},")
    w(f"            raw: {sw(s['raw'])},")
    w(f"            wordCount: {s['wordCount']},")
    w(f"            requiredAll: {json.dumps(s['requiredAll'], ensure_ascii=False)},")
    w(f"            requiredAny: {json.dumps(s['requiredAny'], ensure_ascii=False)},")
    w(f"            forbidden: {json.dumps(s['forbidden'], ensure_ascii=False)},")
    dims_repr = []
    for k in ("facts", "grammar", "terms", "format", "novel"):
        d = s["dimensions"][k]
        dims_repr.append(f"{k}: A1DimAssert(requiredAny: {json.dumps(d['requiredAny'], ensure_ascii=False)}, forbidden: {json.dumps(d['forbidden'], ensure_ascii=False)})")
    w("            dims: A1Dims(")
    for j, repr_line in enumerate(dims_repr):
        suffix = "," if j < len(dims_repr) - 1 else ""
        w(f"                {repr_line}{suffix}")
    w("            )")
    w("        ),")

w("    ]")
w("")
w("    private let executableIDs: Set<String> = " + json.dumps(exec_ids) )
w("")
w("    // MARK: - fixture integrity (no pipeline, CPU-light) — all 200 samples")
w("")
w("    func testFullCorpusFixtureIntegrity() {")
w("        XCTAssertEqual(corpus.count, 200)")
w("        XCTAssertEqual(corpus.filter { $0.tier == \"short\" }.count, 100)")
w("        XCTAssertEqual(corpus.filter { $0.tier == \"long\" }.count, 100)")
w("        XCTAssertEqual(Set(corpus.map(\\.id)).count, 200, \"duplicate sample ids\")")
w("        XCTAssertEqual(executableIDs.count, 20)")
w("        for s in corpus {")
w("            XCTAssertFalse(s.raw.isEmpty, \"\\(s.id) empty raw\")")
w("            XCTAssertFalse(s.requiredAll.isEmpty, \"\\(s.id) no required facts\")")
w("            if s.tier == \"short\" {")
w("                XCTAssertTrue((45...60).contains(s.wordCount), \"\\(s.id) short wordCount \\(s.wordCount)\")")
w("            } else {")
w("                XCTAssertTrue((140...150).contains(s.wordCount), \"\\(s.id) long wordCount \\(s.wordCount)\")")
w("            }")
w("            for group in s.requiredAny { XCTAssertFalse(group.isEmpty, \"\\(s.id) empty requiredAny group\") }")
w("            // a forbidden token must not also be required")
w("            for f in s.forbidden {")
w("                XCTAssertFalse(s.requiredAll.contains(f), \"\\(s.id) contradictory assertion: \\(f)\")")
w("            }")
w("        }")
w("    }")
w("")
w("    // MARK: - executed subset (opt-in, real pipeline, recorded verdicts)")
w("")
w("    func testExecutedSubsetScores() async throws {")
w("        guard ProcessInfo.processInfo.environment[\"SUPERFLOW_CORPUS_EXECUTE\"] == \"1\" else {")
w("            throw XCTSkip(\"Set SUPERFLOW_CORPUS_EXECUTE=1 to run the 20-sample executed subset.\")")
w("        }")
w("        var settings = AppSettings.default")
w("        // Documented deterministic Tier-0 fallback: no S1-mini, no mocks.")
w("        settings.cleanupEnabled = false")
w("        let pipeline = TextPipelineBuilder.make(settings: settings)")
w("        let context = TextContext(settings: settings)")
w("        let selected = corpus.filter { executableIDs.contains($0.id) }")
w("        XCTAssertEqual(selected.count, 20)")
w("")
w("        var records: [[String: Any]] = []")
w("        for s in selected {")
w("            let result = await pipeline.run(s.raw, context: context)")
w("            let out = result.text")
w("            XCTAssertFalse(out.isEmpty, \"\\(s.id) pipeline produced empty output\")")
w("            var dimScores: [String: Bool] = [:]")
w("            let allDims: [(String, A1DimAssert)] = [")
w("                (\"facts\", s.dims.facts), (\"grammar\", s.dims.grammar), (\"terms\", s.dims.terms),")
w("                (\"format\", s.dims.format), (\"novel\", s.dims.novel)]")
w("            for (name, assertion) in allDims {")
w("                let reqOK = assertion.requiredAny.allSatisfy { group in")
w("                    group.contains { a1Contains(out, $0) }")
w("                }")
w("                let forbOK = assertion.forbidden.allSatisfy { !a1Contains(out, $0) }")
w("                dimScores[name] = reqOK && forbOK")
w("            }")
w("            let factsOK = s.requiredAll.allSatisfy { a1Contains(out, $0) }")
w("            let anyOK = s.requiredAny.allSatisfy { group in")
w("                group.contains { a1Contains(out, $0) }")
w("            }")
w("            let forbOK = s.forbidden.allSatisfy { !a1Contains(out, $0) }")
w("            records.append([")
w("                \"id\": s.id, \"tier\": s.tier, \"domain\": s.domain,")
w("                \"executed\": true, \"wordCount\": s.wordCount,")
w("                \"raw\": s.raw, \"output\": out,")
w("                \"coreFactsOK\": factsOK, \"coreAnyOK\": anyOK, \"coreForbiddenOK\": forbOK,")
w("                \"dimensions\": dimScores")
w("            ])")
w("        }")
w("")
w("        let payload: [String: Any] = [\"path\": \"Tier0-deterministic\", \"count\": records.count, \"records\": records]")
w("        let data = try JSONSerialization.data(withJSONObject: payload, options: [.prettyPrinted, .sortedKeys])")
w("        let outPath = ProcessInfo.processInfo.environment[\"SUPERFLOW_CORPUS_OUTPUT\"]")
w("            ?? (FileManager.default.temporaryDirectory.appendingPathComponent(\"agent1-executed.json\").path)")
w("        try data.write(to: URL(fileURLWithPath: outPath))")
w("        NSLog(\"AGENT1_EXECUTED_WRITTEN \\(outPath) records=\\(records.count)\")")
w("    }")
w("}")
w("")

path = "/Users/harshitduggal/workspace/superflow/Packages/L2-Engines/TextPipeline/Tests/TextPipelineTests/AggressiveCorpusShortTests.swift"
with open(path, "w", encoding="utf-8") as f:
    f.write("\n".join(lines))
print("wrote", path, "lines", len(lines), "exec_ids", len(exec_ids))
print(exec_ids)
