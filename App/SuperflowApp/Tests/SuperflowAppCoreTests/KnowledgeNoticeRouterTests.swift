import Foundation
import SuperflowFeatureIsland
import SuperflowKernel
import SuperflowStorageSQLite
import SuperflowTextPipeline
import XCTest
@testable import SuperflowAppCore

private struct LearningTestFeed: IslandFeed {
    var events: AsyncStream<IslandEvent> { AsyncStream { $0.finish() } }
    var levels: AsyncStream<Float> { AsyncStream { $0.finish() } }
    var storesTranscripts: Bool { true }
    func lastTranscript() -> IslandTranscript? { nil }
}

@MainActor
final class KnowledgeNoticeRouterTests: XCTestCase {
    func testOnlyCommittedKnowledgeRulesNotifyAndUndoDeletesPersistedRule() async throws {
        let directory = FileManager.default.temporaryDirectory
            .appendingPathComponent("knowledge-notice-\(UUID().uuidString)", isDirectory: true)
        try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
        defer { try? FileManager.default.removeItem(at: directory) }

        let store = try SQLiteStore(path: directory.appendingPathComponent("db.sqlite").path)
        let learning = DictionaryLearningEngine(learning: store, lexicon: store)
        let island = IslandModel(feed: LearningTestFeed(), geometry: NotchGeometry(
            frame: CGRect(x: 0, y: 0, width: 1728, height: 1117),
            safeTop: 38, leftWidth: 704, rightWidth: 704, scale: 2))
        var soundCount = 0
        island.playMilestoneSound = { soundCount += 1 }
        let router = KnowledgeNoticeRouter(learning: learning, island: island)
        island.noticeAction = { [router] notice in router.handle(notice) }
        await learning.setOnApplied { [weak router] candidate, active in
            await router?.applied(candidate, active: active)
        }

        let pending = try await learning.observe(
            ObservedCorrection(heard: "next year", corrected: "Next.js",
                               appBundleID: "com.apple.TextEdit", anchorID: "a"),
            consent: true)
        let candidate = try XCTUnwrap(pending)
        XCTAssertEqual(island.phase, .idle, "Unconfirmed suggestions must not notify.")

        try await learning.confirm(id: candidate.id)
        let entries = try await store.lexicon()
        XCTAssertTrue(entries.contains { $0.id == candidate.id && $0.canonical == "Next.js" })
        let notice = IslandNotice(kind: .knowledge, title: "Added to Knowledge",
                                  detail: "next year → Next.js", action: "Undo")
        // Notice has a fresh postedAt generated by the router, so extract the
        // actual event instead of constructing a timestamp-sensitive equality.
        guard case .notice(let actual) = island.phase else {
            return XCTFail("A successfully saved correction must appear on the Island.")
        }
        XCTAssertEqual(actual.kind, notice.kind)
        XCTAssertEqual(actual.title, notice.title)
        XCTAssertEqual(actual.detail, notice.detail)
        XCTAssertEqual(actual.action, "Undo")
        XCTAssertEqual(soundCount, 1)

        island.noticeAction(actual)
        for _ in 0..<100 {
            let rules = try await store.lexicon()
            if rules.allSatisfy({ $0.id != candidate.id }) { break }
            try await Task.sleep(for: .milliseconds(10))
        }
        let remaining = try await store.lexicon()
        XCTAssertFalse(remaining.contains { $0.id == candidate.id })
        XCTAssertEqual(soundCount, 1, "Removing a correction must not play completion again.")
    }
}
