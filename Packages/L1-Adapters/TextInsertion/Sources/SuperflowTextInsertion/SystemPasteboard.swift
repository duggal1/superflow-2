import AppKit
import Foundation

/// Clipboard seam. Async so the insertion actor can call it without blocking,
/// and so tests can substitute an in-memory board.
public protocol PasteboardAccess: Sendable {
    func changeCount() async -> Int
    /// Writes `text` with the nspasteboard.org markers. Returns the board's
    /// change count after the write, or nil when the write failed.
    func writeTransient(_ text: String) async -> Int?
    func snapshot(maxBytes: Int) async -> PasteboardSnapshot?
    func restore(_ snapshot: PasteboardSnapshot, ifChangeCount expected: Int) async
}

/// Production clipboard. `NSPasteboard` is documented as thread-safe; the
/// unchecked conformance keeps it usable from the insertion actor.
public final class SystemPasteboard: PasteboardAccess, @unchecked Sendable {
    private let pasteboard: NSPasteboard

    public init(pasteboard: NSPasteboard = .general) {
        self.pasteboard = pasteboard
    }

    public func changeCount() async -> Int {
        pasteboard.changeCount
    }

    public func writeTransient(_ text: String) async -> Int? {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        guard item.setString(text, forType: .string) else { return nil }
        // Empty data is the nspasteboard.org convention. Clipboard managers look
        // for the type, not for a non-empty value.
        let marker = Data()
        for raw in ["org.nspasteboard.TransientType",
                    "org.nspasteboard.ConcealedType",
                    "org.nspasteboard.AutoGeneratedType"] {
            _ = item.setData(marker, forType: NSPasteboard.PasteboardType(raw))
        }
        guard pasteboard.writeObjects([item]) else { return nil }
        return pasteboard.changeCount
    }

    public func snapshot(maxBytes: Int) async -> PasteboardSnapshot? {
        PasteboardSnapshot(pasteboard: pasteboard, maxBytes: maxBytes)
    }

    public func restore(_ snapshot: PasteboardSnapshot, ifChangeCount expected: Int) async {
        snapshot.restore(into: pasteboard, onlyIfChangeCount: expected)
    }
}

public extension NSPasteboard.PasteboardType {
    static let superflowTransient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    static let superflowConcealed = NSPasteboard.PasteboardType("org.nspasteboard.ConcealedType")
    static let superflowAutoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
}
