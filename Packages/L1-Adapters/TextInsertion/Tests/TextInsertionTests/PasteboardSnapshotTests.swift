import AppKit
import XCTest
@testable import SuperflowTextInsertion

final class PasteboardSnapshotTests: XCTestCase {
    private var pasteboard: NSPasteboard!

    override func setUp() {
        pasteboard = NSPasteboard(name: NSPasteboard.Name("com.superflow.tests.\(UUID().uuidString)"))
    }

    override func tearDown() {
        pasteboard.releaseGlobally()
    }

    func testRestoresEveryTypeWhenChangeCountMatches() {
        pasteboard.clearContents()
        let item = NSPasteboardItem()
        item.setString("original", forType: .string)
        item.setData(Data([1, 2, 3]), forType: .png)
        pasteboard.writeObjects([item])
        let snapshot = PasteboardSnapshot(pasteboard: pasteboard)

        pasteboard.clearContents()
        pasteboard.setString("transient", forType: .string)
        snapshot.restore(into: pasteboard, onlyIfChangeCount: pasteboard.changeCount)

        XCTAssertEqual(pasteboard.string(forType: .string), "original")
        XCTAssertEqual(pasteboard.data(forType: .png), Data([1, 2, 3]))
        XCTAssertTrue(snapshot.isComplete)
    }

    func testRefusesToClobberNewerWrite() {
        pasteboard.clearContents()
        pasteboard.setString("original", forType: .string)
        let snapshot = PasteboardSnapshot(pasteboard: pasteboard)
        pasteboard.clearContents()
        pasteboard.setString("someone else", forType: .string)
        snapshot.restore(into: pasteboard, onlyIfChangeCount: pasteboard.changeCount - 1)
        XCTAssertEqual(pasteboard.string(forType: .string), "someone else")
    }

    func testIncompleteSnapshotIsNeverRestored() {
        pasteboard.clearContents()
        pasteboard.setString("current", forType: .string)
        let incomplete = PasteboardSnapshot(
            items: [[.init(type: NSPasteboard.PasteboardType.string.rawValue, data: Data("old".utf8))]],
            isComplete: false)
        incomplete.restore(into: pasteboard, onlyIfChangeCount: pasteboard.changeCount)
        XCTAssertEqual(pasteboard.string(forType: .string), "current")
    }

    func testOversizedBoardIsMarkedIncomplete() {
        pasteboard.clearContents()
        pasteboard.setString(String(repeating: "x", count: 2_048), forType: .string)
        let snapshot = PasteboardSnapshot(pasteboard: pasteboard, maxBytes: 1_024)
        XCTAssertFalse(snapshot.isComplete)
        XCTAssertTrue(snapshot.items.isEmpty)
    }

    func testTransientWriteSetsAllMarkersAndReturnsChangeCount() async {
        let system = SystemPasteboard(pasteboard: pasteboard)
        let expected = await system.changeCount()
        let written = await system.writeTransient("hello")
        XCTAssertEqual(written, expected + 1)
        XCTAssertEqual(pasteboard.string(forType: .string), "hello")
        XCTAssertEqual(pasteboard.data(forType: .superflowTransient), Data())
        XCTAssertEqual(pasteboard.data(forType: .superflowConcealed), Data())
        XCTAssertEqual(pasteboard.data(forType: .superflowAutoGenerated), Data())
    }
}
